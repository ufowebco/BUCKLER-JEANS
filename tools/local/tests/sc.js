const { chromium } = require('playwright');
const ok = (c, m) => console.log((c ? 'OK   ' : 'FAIL ') + m);
(async () => {
  const b = await chromium.launch(); const errs = [];
  const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
  p.on('pageerror', e => errs.push(e.message));
  let posts = 0; p.on('request', r => { if (r.method() === 'POST' && /add-item/.test(r.url())) posts++; });
  await p.goto('http://localhost:8899/product/jean-bota-campana-flare-dama-tiro-alto/', { waitUntil: 'networkidle' });
  await p.selectOption('#pa_tallas-plus-size', '16'); await p.waitForTimeout(400);
  const navs = []; p.on('framenavigated', f => { if (f === p.mainFrame()) navs.push(f.url()); });
  await p.click('.single_add_to_cart_button');
  await p.waitForSelector('#bk-sc.is-open', { timeout: 8000 }).catch(() => {});
  ok(await p.isVisible('#bk-sc .bk-sc__panel'), 'añadir en la ficha abre el carrito flotante');
  ok(navs.length === 0, 'sin recargar la página');
  await p.waitForSelector('.bk-sc__item'); 
  ok((await p.textContent('.bk-sc__item')).includes('Talla: 16'), 'item con su talla');
  await p.waitForSelector('[data-bk-sc-suggest]:not([hidden])', { timeout: 8000 }).catch(() => {});
  const sugTitle = await p.textContent('.bk-sc__stitle').catch(() => '');
  const sugs = await p.locator('.bk-sc__sname').allTextContents();
  ok(/talla 16/i.test(sugTitle) && sugs.length > 0 && !sugs.some(s => /FLARE/.test(s)), `sugerencias "${sugTitle}": ${sugs.join(' | ')}`);
  ok(!sugs.some(s => /SHORT/.test(s)), 'solo línea Curvy (no aparece el short Slim)');
  ok((await p.textContent('#bk-sc [data-bk-sc-foot]')).includes('cuotas'), 'total y cuota Addi en el pie');
  await p.locator('.bk-sc__btn--add').first().click();
  await p.waitForFunction(() => document.querySelectorAll('.bk-sc__item').length === 2, null, { timeout: 8000 }).catch(() => {});
  ok(await p.locator('.bk-sc__item').count() === 2, 'añadir sugerida en un toque (2 productos)');
  const hc = await p.textContent('[data-bk-cart-count]');
  ok(hc.trim() === '2', 'contador del header = ' + hc.trim());
  // Rage click en +: 4 clics rápidos
  const inc = p.locator('.bk-sc__item').first().locator('[data-act="inc"]');
  for (let i = 0; i < 4; i++) await inc.click({ force: true, noWaitAfter: true }).catch(() => {});
  await p.waitForTimeout(1500);
  const q = await p.locator('.bk-sc__item').first().locator('.bk-sc__qty span').textContent();
  ok(q === '2', 'rage click en "+" suma solo 1 (cantidad ' + q + ')');
  await p.locator('.bk-sc__item').first().locator('[data-act="remove"]').click();
  await p.waitForFunction(() => document.querySelectorAll('.bk-sc__item').length === 1, null, { timeout: 8000 }).catch(() => {});
  ok(await p.locator('.bk-sc__item').count() === 1, 'quitar producto');
  await p.screenshot({ path: '/tmp/claude-0/bk-local/sc-1440.png' });
  await p.keyboard.press('Escape'); await p.waitForTimeout(400);
  ok(await p.locator('#bk-sc').isHidden(), 'Escape cierra');
  await p.click('[data-bk-cart]'); await p.waitForSelector('#bk-sc.is-open');
  ok(p.url().includes('/product/'), 'icono del carrito abre el panel sin navegar');
  ok(await p.evaluate(() => document.activeElement.closest('#bk-sc') !== null), 'foco dentro del panel');
  await p.locator('[data-act="remove"]').click();
  await p.waitForSelector('.bk-sc__empty');
  ok((await p.textContent('.bk-sc__empty')).includes('Línea Curvy'), 'carrito vacío con accesos a las líneas');
  // Móvil
  const m = await (await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })).newPage();
  m.on('pageerror', e => errs.push(e.message));
  await m.goto('http://localhost:8899/product/jean-bota-campana-flare-dama-tiro-alto/', { waitUntil: 'networkidle' });
  await m.selectOption('#pa_tallas-plus-size', '22'); await m.waitForTimeout(300);
  await m.click('.single_add_to_cart_button'); await m.waitForSelector('.bk-sc__item'); await m.waitForTimeout(1200);
  await m.screenshot({ path: '/tmp/claude-0/bk-local/sc-390.png' });
  const w = await m.evaluate(() => document.querySelector('.bk-sc__panel').getBoundingClientRect().width);
  ok(w <= 390, 'panel ocupa el ancho del celular: ' + w);
  ok(errs.length === 0, 'sin errores JS ' + errs.join(' | '));
  await b.close();
})();
